#: The wavelets this module has filters for, in table order.
WAVELET_FAMILIES: Final[tuple[str, ...]] = tuple(_SCALING)


class _FilterBank(NamedTuple):
    """The four filters of an orthogonal wavelet: analysis ``dec_*`` and synthesis ``rec_*``, low and high pass."""

    dec_lo: tuple[float, ...]
    dec_hi: tuple[float, ...]
    rec_lo: tuple[float, ...]
    rec_hi: tuple[float, ...]

    @property
    def length(self) -> int:
        """The number of taps of each filter."""
        return len(self.rec_lo)


def _filter_bank(name: str) -> _FilterBank:
    """The filters of the wavelet ``name``.

    Parameters
    ----------
    name : str
        One of ``WAVELET_FAMILIES``.

    Returns
    -------
    _FilterBank
        Built from the scaling filter by the quadrature-mirror relations.

    Raises
    ------
    ValueError
        ``name`` is not a wavelet this module has a table for.
    """
    scaling = _SCALING.get(name)
    if scaling is None:
        raise ValueError(
            f"No filters for wavelet {name!r}; the filters of this build are {', '.join(WAVELET_FAMILIES)}"
        )
    taps = len(scaling)
    rec_lo = scaling
    rec_hi = tuple((-1) ** k * scaling[taps - 1 - k] for k in range(taps))
    return _FilterBank(rec_lo[::-1], rec_hi[::-1], rec_lo, rec_hi)
