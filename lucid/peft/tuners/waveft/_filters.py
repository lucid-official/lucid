r"""The orthogonal wavelet filters WaveFT builds its update from: the scaling filter of each family, and the three others it fixes.

A wavelet of an orthogonal family is given by its scaling (low-pass) filter :math:`h_0 \ldots h_{L-1}`:
the conditions on it are :math:`\sum_k h_k = \sqrt 2` and the double-shift orthonormality
:math:`\sum_k h_k h_{k+2m} = \delta_{m0}`, and the family says how many moments of the wavelet vanish.
The wavelet (high-pass) filter is its quadrature mirror, :math:`g_k = (-1)^k h_{L-1-k}`, and the
analysis filters are the synthesis ones read backwards.  The tables below are the scaling filters in
the convention the reference library writes them in (its synthesis low-pass, "rec_lo").

* ``dbN`` (Daubechies, :math:`L = 2N`): :math:`N` vanishing moments.  The filter factors as
  :math:`H(\omega) = \sqrt 2\,\cos^N(\omega/2)\,Q(\omega)` with :math:`|Q|^2` the Daubechies polynomial
  :math:`P(\sin^2(\omega/2)) = \sum_{k<N}\binom{N-1+k}{k}\sin^{2k}(\omega/2)`, taking the root choice
  of extremal phase, which puts the energy at the front of the filter.
* ``symN`` (symlets, :math:`L = 2N`): the same :math:`N` moments and the same :math:`|H|`, with the root
  choice whose phase departs least from a straight line through the origin; listed in the orientation
  of Daubechies' tables (a filter and its mirror image are equally symmetric).
* ``coifN`` (coiflets, :math:`L = 6N`): :math:`2N` vanishing wavelet moments and
  :math:`\sum_k (k-2N)^m h_k = 0` for :math:`m = 1 \ldots 2N-1`, the scaling function's moments.

Each table was found by solving those definitions at sixty digits (spectral factorisation of the
Daubechies polynomial and a search over its root choices for the symlets; Newton's method on the
moment equations for the coiflets, started from an approximate table to choose among their several
solutions) and rounded to a double.  ``test_waveft.py`` re-checks every defining property of every
table — orthonormality, the sum, the vanishing moments, the Daubechies identity for :math:`|H|^2`, the
phase — so a digit that drifts is caught without a second copy of the numbers.
"""

