def _annotation_for_param(name: str, ann: object, entry: object, kind: object) -> str:
    """Pick a stub-friendly annotation for a wrapper parameter.

    The runtime ``__signature__`` rarely carries annotations (most wrappers
    inherit from a body with bare names), so we infer from the parameter
    name via ``_PARAM_TYPE_MAP``.  Honours an explicit annotation if one
    *is* present (adapters with proper signatures).
    """
    import inspect as _inspect

    from lucid._ops._registry import OpEntry

    assert isinstance(entry, OpEntry)
    if ann is not _inspect.Parameter.empty:
        return _stringify_annotation(ann)

    n = entry.n_tensor_args

    # ``*shape`` / ``*sizes`` / ``*dims`` variadic — single ints.
    if kind == _inspect.Parameter.VAR_POSITIONAL:
        if name in {"shape", "sizes", "size", "dims"}:
            return "int"
        return "object"

    # List-style ops: the first slot is the tensor list.
    if n == -1 and name == "tensors":
        return "list[Tensor]"

    if name in _PARAM_TYPE_MAP:
        return _PARAM_TYPE_MAP[name]

    # Final guard — never emit ``Any``.  Unknown role → opaque ``object``.
    return "object"


def _stringify_annotation(ann: object) -> str:
    """Convert a runtime annotation to a stub-friendly string."""
    import re as _re
    import typing as _typing

    # ForwardRef instances stringify with their evaluation owner (whose
    # address rotates every interpreter run) — collapse to the bare name.
    if isinstance(ann, _typing.ForwardRef):
        return ann.__forward_arg__

    raw = repr(ann) if not isinstance(ann, str) else ann
    raw = raw.replace("<class '", "").replace("'>", "")
    raw = raw.replace("typing.", "")
    raw = raw.replace("collections.abc.", "")
    raw = raw.replace("lucid._tensor.tensor.Tensor", "Tensor")
    raw = raw.replace("lucid._C.engine.TensorImpl", "Tensor")
    raw = raw.replace("lucid._C._engine.TensorImpl", "Tensor")
    # Every stub imports the engine as ``_C_engine`` (H2), never as ``lucid``.
    raw = raw.replace("lucid._C.engine.", "_C_engine.")
    raw = raw.replace("lucid._dtype.dtype", "dtype")
    raw = raw.replace("lucid._device.device", "device")
    raw = raw.replace("_DType", "dtype")
    raw = raw.replace("NoneType", "None")
    # Strip the ``ForwardRef('Name', owner=<function … at 0xADDR>)``
    # debug repr that leaks into stubs when ``Format.FORWARDREF`` parses an
    # adapter's TYPE_CHECKING annotation.  Keep only the name inside quotes.
    raw = _re.sub(
        r"ForwardRef\(\s*'([^']+)'(?:\s*,[^)]*)?\)",
        r"\1",
        raw,
    )
    # The literal string ``Any`` is forbidden in this codebase's stubs —
    # replace with ``object`` if it sneaks in via a dependency type repr.
    raw = raw.replace(" Any ", " object ").replace("[Any]", "[object]")
    if raw.strip() == "Any":
        raw = "object"
    return raw


def _avoid_dtype_shadow(sig: str) -> str:
    """Rewrite builtin scalar types to the ``_int`` / ``_float`` / ``_bool``
    aliases in a generated ``__init__.pyi`` signature.

    ``lucid``'s public top-level dtype aliases (``int = int32``,
    ``float = float32``, ``bool = bool_`` — see ``_INIT_HEADER``) shadow the
    builtins at module scope, so a bare ``: int`` annotation would wrongly
    resolve to the ``int32`` dtype for external type checkers.  The private
    ``_int`` / ``_float`` / ``_bool`` aliases (defined at the top of
    ``_INIT_HEADER``) point at the real builtins.  Word boundaries keep
    ``int32`` / ``bool_`` / ``float_power`` and similar identifiers untouched.

    Only applied to ``__init__.pyi`` signatures (the engine / tensor stubs do
    not define the shadowing aliases).
    """
    import re as _re

    return _re.sub(r"\b(int|float|bool)\b", r"_\1", sig)


def _sig_from_callable(name: str, fn: object) -> str:
    """Generate a stub line from a live callable via AST source parsing.

    Python 3.14 evaluates annotations lazily (PEP 649): accessing
    ``__annotations__`` or calling ``inspect.signature()`` on a function
    whose annotations reference TYPE_CHECKING-only names raises
    ``NameError``.  We therefore parse the *source text* via ``ast`` —
    which never evaluates anything — and emit annotation strings verbatim.

    Falls back to a name-inferred signature (using ``_PARAM_TYPE_MAP``)
    when source is unavailable (built-ins, C extensions, lambdas).  Never
    emits ``*args`` / ``**kwargs`` — these are forbidden in stubs (H9).
    """
    import inspect
    import textwrap

    # ── Try AST-based extraction (preferred, annotation-safe) ────────────
    try:
        raw_src = inspect.getsource(fn) if callable(fn) else ""
        src = textwrap.dedent(raw_src)
        tree = ast.parse(src) if src else None
    except Exception:
        tree = None

    if tree is not None:
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if node.name != name:
                continue
            return _sig_from_ast(name, node)

    # ── Fallback: code-object introspection (no annotation evaluation) ───
    code = getattr(fn, "__code__", None)
    if code is None:
        # Absolute last resort for built-ins / C callables.
        return f"def {name}(input: Tensor, /) -> Tensor: ..."

    n_all = code.co_argcount
    n_posonly = code.co_posonlyargcount
    n_kwonly = code.co_kwonlyargcount
    has_varargs = bool(code.co_flags & 0x04)
    has_varkw = bool(code.co_flags & 0x08)

    all_names = code.co_varnames
    pos_kw_names = list(all_names[:n_all])
    kwonly_start = n_all + (1 if has_varargs else 0)
    kwonly_names = list(all_names[kwonly_start : kwonly_start + n_kwonly])

    defaults: tuple[object, ...] = getattr(fn, "__defaults__", None) or ()
    kwdefaults: dict[str, object] = getattr(fn, "__kwdefaults__", None) or {}

    parts: list[str] = []
    default_offset = n_all - len(defaults)

    for i, pname in enumerate(pos_kw_names[:n_posonly]):
        ptype = _PARAM_TYPE_MAP.get(pname, "object")
        sfx = " = ..." if i >= default_offset else ""
        parts.append(f"{pname}: {ptype}{sfx}")
    if n_posonly:
        parts.append("/")
    for i, pname in enumerate(pos_kw_names[n_posonly:], n_posonly):
        ptype = _PARAM_TYPE_MAP.get(pname, "object")
        sfx = " = ..." if i >= default_offset else ""
        parts.append(f"{pname}: {ptype}{sfx}")

    # *args are genuinely variadic only if the source truly has them; the
    # fallback code-object path treats them as unknown — skip (H9).
    if has_varargs and not has_varkw and not kwonly_names:
        varargs_name = all_names[n_all]
        ptype = _PARAM_TYPE_MAP.get(varargs_name, "object")
        parts.append(f"*{varargs_name}: {ptype}")
    elif kwonly_names:
        parts.append("*")

    for pname in kwonly_names:
        ptype = _PARAM_TYPE_MAP.get(pname, "object")
        sfx = " = ..." if pname in kwdefaults else ""
        parts.append(f"{pname}: {ptype}{sfx}")

    # **kwargs: skip entirely per H9 (fallback path only).

    ret = _RETURN_TYPE_MAP.get(name, "Tensor")
    return f"def {name}({', '.join(parts)}) -> {ret}: ..."


