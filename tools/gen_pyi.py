def _engine_strip(t: str, *, collapse_tensor_tuples: bool = False) -> str:
    """Normalise a pybind11 type string for use inside ``engine.pyi``."""
    for prefix in (
        "lucid._C.engine.utils.tokenizer.",
        "lucid._C.engine.coreml.",
        "lucid._C.engine.compile.",
        "lucid._C.engine.",
        "collections.abc.",
        "typing.",
    ):
        t = t.replace(prefix, "")
    t = t.replace("NoneType", "None")
    t = re.sub(r'Annotated\[([^,]+),\s*"FixedSize\(\d+\)"\]', r"\1", t)
    t = t.replace(" | SupportsIndex", "").replace("SupportsIndex | ", "")
    if collapse_tensor_tuples:
        t = t.replace("tuple[TensorImpl, TensorImpl, TensorImpl]", "tuple")
        t = t.replace("tuple[TensorImpl, TensorImpl]", "tuple")
    return t


def _split_top_params(params_raw: str) -> list[str]:
    params: list[str] = []
    depth = 0
    cur = ""
    for ch in params_raw + ",":
        if ch == "," and depth == 0:
            piece = cur.strip()
            cur = ""
            if piece:
                params.append(piece)
        else:
            if ch in "[(":
                depth += 1
            elif ch in "])":
                depth -= 1
            cur += ch
    return params


def _refine_param_type(pname: str, ann: str, default_part: str | None) -> str:
    if pname == "generator" and ann == "object":
        return "Generator | None"
    if pname in ("h0", "c0") and ann == "object":
        return "TensorImpl | None"
    if (pname, ann) in _NULLABLE_SHARED_PTR_PARAMS:
        return f"{ann} | None"
    if default_part == "None" and ann != "object" and "None" not in ann:
        return f"{ann} | None"
    return ann


def _format_engine_param(piece: str, *, is_method: bool = False, is_first: bool = False) -> str:
    default_part: str | None = None
    if "=" in piece:
        head, default_part = piece.split("=", 1)
        head = head.strip()
        default_part = default_part.strip()
    else:
        head = piece.strip()

    if ":" in head:
        pname, ann_raw = head.split(":", 1)
        pname = pname.strip()
        if is_method and is_first and pname == "self":
            return "self"
        ann = _refine_param_type(pname, _engine_strip(ann_raw.strip()), default_part)
        rendered = f"{pname}: {ann}"
    else:
        if is_method and is_first and head == "self":
            return "self"
        rendered = f"{head}: object" if head in ("*args", "**kwargs") else head

    return f"{rendered} = ..." if default_part is not None else rendered


def _strip_leading_defaults(params: list[str], *, is_method: bool) -> None:
    last_no_default = -1
    for i, p in enumerate(params):
        if i == 0 and is_method and p == "self":
            continue
        if "= ..." not in p and not p.startswith("*") and p != "/":
            last_no_default = i
    for i in range(last_no_default):
        if params[i].endswith(" = ...") and not params[i].startswith("*"):
            params[i] = params[i][: -len(" = ...")]


def _parse_sig_line(
    name: str,
    line: str,
    *,
    qualname: str = "",
    is_method: bool = False,
    collapse_tensor_tuples: bool = False,
) -> str | None:
    m = re.match(
        rf"^(?:\d+\.\s*)?{re.escape(name)}\((?P<params>.*)\)\s*->\s*(?P<ret>.+?)\s*$",
        line.strip(),
    )
    if not m:
        return None
    raw_pieces = _split_top_params(m.group("params").strip())
    params = [
        _format_engine_param(p, is_method=is_method, is_first=(i == 0))
        for i, p in enumerate(raw_pieces)
    ]
    _strip_leading_defaults(params, is_method=is_method)
    ret = _RET_OVERRIDES.get(
        qualname,
        _engine_strip(m.group("ret").strip(), collapse_tensor_tuples=collapse_tensor_tuples),
    )
    return f"({', '.join(params)}) -> {ret}"


def _callable_sigs(
    name: str,
    fn: object,
    *,
    qualname: str = "",
    is_method: bool = False,
    collapse_tensor_tuples: bool = False,
) -> list[str]:
    if qualname in _SIG_OVERRIDES:
        return [_SIG_OVERRIDES[qualname]]
    if name in _SIG_OVERRIDES:
        return [_SIG_OVERRIDES[name]]
    doc = getattr(fn, "__doc__", "") or ""
    lines = doc.splitlines()
    if "Overloaded function." in doc:
        overloads = [
            parsed
            for line in lines
            if re.match(r"^\s*\d+\.\s*" + re.escape(name) + r"\(", line)
            and (
                parsed := _parse_sig_line(
                    name,
                    line,
                    qualname=qualname,
                    is_method=is_method,
                    collapse_tensor_tuples=collapse_tensor_tuples,
                )
            )
            is not None
        ]
        if overloads:
            return overloads
    first = lines[0] if lines else ""
    parsed = _parse_sig_line(
        name,
        first,
        qualname=qualname,
        is_method=is_method,
        collapse_tensor_tuples=collapse_tensor_tuples,
    )
    if parsed is not None:
        return [parsed]
    return ["(input: TensorImpl, /, *args: object, **kwargs: object) -> TensorImpl"]


def _is_pybind_enum(cls: type) -> bool:
    return any(isinstance(v, cls) for v in cls.__dict__.values())


def _class_base_str(cls: type) -> str:
    bases: list[str] = []
    for b in cls.__bases__:
        if b.__name__ in ("pybind11_object", "object"):
            continue
        if b.__module__ == "builtins" and b.__name__ != "RuntimeError":
            bases.append(f"builtins.{b.__name__}")
        else:
            bases.append(b.__name__)
    return f"({', '.join(bases)})" if bases else ""


def _render_enum_body(cls: type, sub_indent: str) -> list[str]:
    cname = cls.__name__
    body = [f"{sub_indent}{k}: {cname}" for k, v in cls.__dict__.items() if isinstance(v, cls)]
    if "name" in cls.__dict__:
        body.append(f"{sub_indent}@property")
        body.append(f"{sub_indent}def name(self) -> str: ...")
    if "value" in cls.__dict__:
        body.append(f"{sub_indent}@property")
        body.append(f"{sub_indent}def value(self) -> int: ...")
    init_raw = cls.__dict__.get("__init__")
    if init_raw is not None and not isinstance(init_raw, type(object.__init__)):
        for sig in _callable_sigs(
            "__init__",
            getattr(cls, "__init__"),
            qualname=f"{cname}.__init__",
            is_method=True,
        ):
            body.append(f"{sub_indent}def __init__{sig}: ...")
    for dunder in ("__int__", "__index__"):
        if dunder in cls.__dict__:
            for sig in _callable_sigs(
                dunder,
                getattr(cls, dunder),
                qualname=f"{cname}.{dunder}",
                is_method=True,
            ):
                body.append(f"{sub_indent}def {dunder}{sig}: ...")
    return body


def _prop_getter_type(cname: str, mname: str, prop: property) -> str:
    if (cname, mname) in _PROP_TYPE_OVERRIDES:
        return _PROP_TYPE_OVERRIDES[(cname, mname)]
    fget_doc = (getattr(prop.fget, "__doc__", "") or "").splitlines()
    first = fget_doc[0] if fget_doc else ""
    m = re.search(r"->\s*(.+?)\s*$", first)
    return _engine_strip(m.group(1)) if m else "object"


def _prop_setter_type(cname: str, mname: str, prop: property, getter_type: str) -> str:
    if (cname, mname) in _PROP_TYPE_OVERRIDES:
        return _PROP_TYPE_OVERRIDES[(cname, mname)]
    fset_doc = (getattr(prop.fset, "__doc__", "") or "").splitlines()
    first = fset_doc[0] if fset_doc else ""
    m = re.match(r"^\([^,]+,\s*[^:]+:\s*(.+)\)\s*->\s*None", first)
    return _engine_strip(m.group(1)) if m else getter_type


def _render_property(cname: str, mname: str, prop: property, sub_indent: str) -> list[str]:
    ptype = _prop_getter_type(cname, mname, prop)
    lines = [
        f"{sub_indent}@property",
        f"{sub_indent}def {mname}(self) -> {ptype}: ...",
    ]
    if prop.fset is not None:
        stype = _prop_setter_type(cname, mname, prop, ptype)
        lines.append(f"{sub_indent}@{mname}.setter")
        lines.append(f"{sub_indent}def {mname}(self, value: {stype}) -> None: ...")
    return lines


def _render_method_member(
    cname: str, mname: str, raw: object, cls: type, sub_indent: str
) -> list[str]:
    qual = f"{cname}.{mname}"
    if isinstance(raw, staticmethod):
        sigs = _callable_sigs(mname, raw.__func__, qualname=qual, is_method=False)
        out: list[str] = []
        for sig in sigs:
            if len(sigs) > 1:
                out.append(f"{sub_indent}@overload")
            out.append(f"{sub_indent}@staticmethod")
            out.append(f"{sub_indent}def {mname}{sig}: ...")
        return out
    attr = getattr(cls, mname, raw)
    sigs = _callable_sigs(mname, attr, qualname=qual, is_method=True)
    out = []
    for sig in sigs:
        if len(sigs) > 1:
            out.append(f"{sub_indent}@overload")
        out.append(f"{sub_indent}def {mname}{sig}: ...")
    return out


def is_stubbed_class_member(mname: str, raw: object) -> bool:
    """Return True if a ``cls.__dict__`` entry belongs in the generated stub."""
    if mname == "_pybind11_conduit_v1_":
        return False
    if mname.startswith("__"):
        if mname not in _ALLOWED_CLASS_DUNDERS:
            return False
        if mname == "__init__" and isinstance(raw, type(object.__init__)):
            return False
        if mname == "__setattr__" and isinstance(raw, type(object.__setattr__)):
            return False
    return True


def _render_class(cls: type, indent: str = "") -> list[str]:
    cname = cls.__name__
    base_str = _class_base_str(cls)
    if issubclass(cls, BaseException):
        return [f"{indent}class {cname}{base_str}: ..."]
    sub_indent = indent + "    "
    if _is_pybind_enum(cls):
        return [f"{indent}class {cname}{base_str}:", *_render_enum_body(cls, sub_indent)]

    body: list[str] = []
    for mname, raw in cls.__dict__.items():
        if not mname.startswith("__") and isinstance(raw, type):
            body.extend(_render_class(raw, indent=sub_indent))
    for mname, raw in cls.__dict__.items():
        if isinstance(raw, type) or not is_stubbed_class_member(mname, raw):
            continue
        if isinstance(raw, property):
            body.extend(_render_property(cname, mname, raw, sub_indent))
        else:
            body.extend(_render_method_member(cname, mname, raw, cls, sub_indent))

    if not body:
        return [f"{indent}class {cname}{base_str}: ..."]
    return [f"{indent}class {cname}{base_str}:", *body]


def _topo_sort_classes(classes: list[type]) -> list[type]:
    by_name = {c.__name__: c for c in classes}
    visited: set[str] = set()
    ordered: list[type] = []

    def visit(c: type) -> None:
        if c.__name__ in visited:
            return
        visited.add(c.__name__)
        for b in c.__bases__:
            if b.__name__ in by_name:
                visit(by_name[b.__name__])
        ordered.append(c)

    for c in classes:
        visit(c)
    return ordered


def _render_subnamespace_member(prefix: str, k: str, val: object) -> list[str]:
    if callable(val):
        qual = f"{prefix}.{k}"
        out: list[str] = []
        for sig in _callable_sigs(k, val, qualname=qual, is_method=False):
            out.append("    @staticmethod")
            out.append(f"    def {k}{sig}: ...")
        return out
    if isinstance(val, int):
        return [f"    {k}: int"]
    if isinstance(val, dict):
        return [f"    {k}: dict[str, int]"]
    if isinstance(val, str):
        return [f"    {k}: str"]
    return []


def _render_subnamespace(prefix: str, ns_class_name: str, mod: types.ModuleType) -> list[str]:
    out: list[str] = []
    mod_classes = _topo_sort_classes(
        [
            getattr(mod, k)
            for k in sorted(dir(mod))
            if not k.startswith("__") and isinstance(getattr(mod, k), type)
        ]
    )
    for cls in mod_classes:
        out.extend(_render_class(cls))
        out.append("")

    submods: list[tuple[str, types.ModuleType]] = []
    for k in sorted(dir(mod)):
        if not k.startswith("__") and isinstance(getattr(mod, k), types.ModuleType):
            sub_mod = getattr(mod, k)
            sub_prefix = f"{prefix}_{k}"
            out.extend(_render_subnamespace(sub_prefix, f"_{sub_prefix}_namespace", sub_mod))
            out.append("")
            submods.append((k, sub_mod))

    body = [f"    {sub_name}: _{prefix}_{sub_name}_namespace" for sub_name, _ in submods]
    for k in sorted(dir(mod)):
        if k.startswith("__"):
            continue
        val = getattr(mod, k)
        if not isinstance(val, (type, types.ModuleType)):
            body.extend(_render_subnamespace_member(prefix, k, val))
    for cls in mod_classes:
        body.append(f"    {cls.__name__} = {cls.__name__}")
    if not body:
        out.append(f"class {ns_class_name}: ...")
    else:
        out.append(f"class {ns_class_name}:")
        out.extend(body)
    return out


def gen_engine_pyi() -> tuple[str, int]:
    from lucid._C import engine as e

    # Every registered schema, then every table row: an engine composite has
    # a row but no schema.
    policy_map: dict[str, tuple[str, str]] = {}
    try:
        for schema in e.op_registry_all():
            policy_map[schema.name] = (str(schema.amp_policy), str(schema.amp_policy_cpu))
        for name, metal, cpu in e.amp_policy_table():
            policy_map[name] = (str(metal), str(cpu))
    except Exception:
        pass

    out: list[str] = [_ENGINE_PREAMBLE]

    top_classes = _topo_sort_classes(
        [
            getattr(e, k)
            for k in sorted(dir(e))
            if not k.startswith("__") and isinstance(getattr(e, k), type)
        ]
    )
    for cls in top_classes:
        out.extend(_render_class(cls))
        out.append("")

    for mod_name in sorted(dir(e)):
        if mod_name.startswith("__") or mod_name == "compile":
            continue
        mod = getattr(e, mod_name)
        if isinstance(mod, types.ModuleType):
            ns_cls = f"_{mod_name}_namespace"
            out.extend(_render_subnamespace(mod_name, ns_cls, mod))
            out.append(f"{mod_name}: {ns_cls}")
            out.append("")

    for k in sorted(dir(e)):
        if k.startswith("__"):
            continue
        val = getattr(e, k)
        if not isinstance(val, (type, types.ModuleType)) and not callable(val):
            out.append(f"{k}: {type(val).__name__}")
    out.append("")

    fn_names = sorted(
        k
        for k in dir(e)
        if not k.startswith("__")
        and k not in SKIP_PRIVATE_ENGINE_FNS
        and not isinstance(getattr(e, k), (type, types.ModuleType))
        and callable(getattr(e, k))
    )
    for name in fn_names:
        fn = getattr(e, name)
        sigs = _callable_sigs(
            name,
            fn,
            qualname=name,
            is_method=False,
            collapse_tensor_tuples=True,
        )
        comment = _amp_policy_comment(name, policy_map)
        for sig in sigs:
            if comment:
                out.append(f"def {name}{sig}:{comment}")
                out.append("    ...")
                out.append("")
            else:
                out.append(f"def {name}{sig}: ...")

    return "\n".join(out) + "\n", len(fn_names)


